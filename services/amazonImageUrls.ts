export const getProductImagesByTitle = (title: string): string[] => {
  const lowerTitle = title.toLowerCase();

  // Equipamiento de Snorkel
  if (lowerTitle.includes('máscara') || lowerTitle.includes('mask')) {
    return REAL_NAUTICAL_IMAGES['snorkel-mask'];
  }
  if (lowerTitle.includes('aletas') || lowerTitle.includes('fins') || lowerTitle.includes('palau')) {
    return REAL_NAUTICAL_IMAGES['snorkel-fins'];
  }
  if (lowerTitle.includes('tubo') || lowerTitle.includes('supernova') || lowerTitle.includes('respirador')) {
    return REAL_NAUTICAL_IMAGES['snorkel-tube'];
  }
  if (lowerTitle.includes('snorkel') && (lowerTitle.includes('kit') || lowerTitle.includes('completo') || lowerTitle.includes('set'))) {
    return REAL_NAUTICAL_IMAGES['snorkel-set'];
  }
  
  // GPS y Navegación
  if (lowerTitle.includes('gps') || lowerTitle.includes('garmin') || lowerTitle.includes('striker') || lowerTitle.includes('echomap')) {
    return REAL_NAUTICAL_IMAGES['gps-nautico'];
  }
  if (lowerTitle.includes('plotter') || lowerTitle.includes('sonda') || lowerTitle.includes('chartplotter')) {
    return REAL_NAUTICAL_IMAGES['plotter-sonda'];
  }
  
  // Seguridad
  if (lowerTitle.includes('chaleco') && lowerTitle.includes('salvavidas')) {
    return REAL_NAUTICAL_IMAGES['chaleco-salvavidas'];
  }
  if (lowerTitle.includes('bengalas') || lowerTitle.includes('emergencia')) {
    return REAL_NAUTICAL_IMAGES['bengalas'];
  }
  if (lowerTitle.includes('botiquín') || lowerTitle.includes('primeros auxilios')) {
    return REAL_NAUTICAL_IMAGES['botiquin'];
  }
  
  // Cámaras y Tecnología
  if (lowerTitle.includes('gopro') || lowerTitle.includes('hero')) {
    return REAL_NAUTICAL_IMAGES['gopro'];
  }
  if (lowerTitle.includes('cámara') && (lowerTitle.includes('sumergible') || lowerTitle.includes('subacuática'))) {
    return REAL_NAUTICAL_IMAGES['camara-subacuatica'];
  }
  if (lowerTitle.includes('cargador') && lowerTitle.includes('solar')) {
    return REAL_NAUTICAL_IMAGES['cargador-solar'];
  }
  
  // Confort
  if (lowerTitle.includes('nevera') || lowerTitle.includes('coleman') || lowerTitle.includes('cooler')) {
    return REAL_NAUTICAL_IMAGES['nevera-portatil'];
  }
  if (lowerTitle.includes('sombrilla') || lowerTitle.includes('parasol') || lowerTitle.includes('toldo')) {
    return REAL_NAUTICAL_IMAGES['sombrilla'];
  }
  
  // Herramientas
  if (lowerTitle.includes('herramientas') || lowerTitle.includes('kit') && lowerTitle.includes('náutico')) {
    return REAL_NAUTICAL_IMAGES['kit-herramientas'];
  }
  
  // Pesca
  if (lowerTitle.includes('caña') || lowerTitle.includes('pesca') || lowerTitle.includes('fishing')) {
    return REAL_NAUTICAL_IMAGES['kit-pesca'];
  }
  
  // Mascotas
  if ((lowerTitle.includes('chaleco') || lowerTitle.includes('flotador')) && (lowerTitle.includes('perro') || lowerTitle.includes('mascota'))) {
    return REAL_NAUTICAL_IMAGES['chaleco-perro'];
  }
  
  // Protección Solar
  if (lowerTitle.includes('protector') && lowerTitle.includes('solar')) {
    return REAL_NAUTICAL_IMAGES['protector-solar'];
  }
  
  // Sostenibilidad y Energía Solar Marina
  if (lowerTitle.includes('panel') && lowerTitle.includes('solar')) {
    if (lowerTitle.includes('marino') || lowerTitle.includes('flexible') || lowerTitle.includes('barco')) {
      return REAL_NAUTICAL_IMAGES['panel-solar-marino'];
    }
    return REAL_NAUTICAL_IMAGES['panel-solar'];
  }
  if (lowerTitle.includes('bateria') || lowerTitle.includes('batería')) {
    if (lowerTitle.includes('litio') || lowerTitle.includes('lifepo4')) {
      return REAL_NAUTICAL_IMAGES['bateria-litio'];
    }
  }
  if (lowerTitle.includes('inversor') && lowerTitle.includes('solar')) {
    return REAL_NAUTICAL_IMAGES['inversor-solar'];
  }
  if (lowerTitle.includes('regulador') && lowerTitle.includes('carga')) {
    return REAL_NAUTICAL_IMAGES['regulador-carga'];
  }
  if (lowerTitle.includes('aerogenerador') || (lowerTitle.includes('generador') && lowerTitle.includes('viento'))) {
    return REAL_NAUTICAL_IMAGES['aerogenerador'];
  }
  if (lowerTitle.includes('desalinizador') || lowerTitle.includes('desaladora')) {
    return REAL_NAUTICAL_IMAGES['desalinizador'];
  }
  if (lowerTitle.includes('led') || lowerTitle.includes('bombilla')) {
    if (lowerTitle.includes('bajo') && lowerTitle.includes('consumo')) {
      return REAL_NAUTICAL_IMAGES['led-bajo-consumo'];
    }
  }
  if (lowerTitle.includes('ventilador') && lowerTitle.includes('solar')) {
    return REAL_NAUTICAL_IMAGES['ventilador-solar'];
  }
  if (lowerTitle.includes('biodegradable') || lowerTitle.includes('ecológico') || lowerTitle.includes('eco-friendly')) {
    return REAL_NAUTICAL_IMAGES['biodegradable'];
  }
  
  // Imágenes por defecto náuticas en alta calidad
  return [
    'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?w=600&h=400&fit=crop&crop=center',
    'https://images.unsplash.com/photo-1544551763-46a013bb70d5?w=600&h=400&fit=crop&crop=center',
    'https://images.unsplash.com/photo-1569263979104-865ab5c6b6c8?w=600&h=400&fit=crop&crop=center'
  ];
}; 